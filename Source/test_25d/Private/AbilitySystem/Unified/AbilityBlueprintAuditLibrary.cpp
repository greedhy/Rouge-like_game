FString UAbilityBlueprintAuditLibrary::DescribeBlueprint(UBlueprint* Blueprint)
{
    auto Report = MakeShared<FJsonObject>();
    Report->SetNumberField(TEXT("schemaVersion"), 1);
#if WITH_EDITOR
    Report->SetBoolField(TEXT("supported"), true);
    if (!IsValid(Blueprint))
    {
        Report->SetBoolField(TEXT("success"), false);
        Report->SetStringField(TEXT("error"), TEXT("A loaded Blueprint is required."));
        return SerializeAudit(Report);
    }
    Report->SetStringField(TEXT("blueprintPath"), Blueprint->GetPathName());
    Report->SetStringField(TEXT("parentClass"), ObjectPath(Blueprint->ParentClass));
    Report->SetStringField(TEXT("generatedClass"), ObjectPath(Blueprint->GeneratedClass));
    Report->SetStringField(TEXT("skeletonClass"), ObjectPath(Blueprint->SkeletonGeneratedClass));
    TArray<UEdGraph*> Graphs;
    Blueprint->GetAllGraphs(Graphs);
    Graphs.RemoveAll(
        [](const UEdGraph* Graph)
        {
            return !IsValid(Graph);
        });
    Graphs.Sort(
        [](const UEdGraph& A, const UEdGraph& B)
        {
            return A.GetPathName() < B.GetPathName();
        });
    TSet<const UEdGraph*> Seen;
    TArray<TSharedPtr<FJsonValue>> Values;
    for (auto* Graph : Graphs)
    {
        if (!Seen.Contains(Graph))
        {
            Seen.Add(Graph);
            Values.Add(MakeShared<FJsonValueObject>(DescribeGraph(*Graph)));
        }
    }
    Report->SetArrayField(TEXT("graphs"), Values);
    TArray<TSharedPtr<FJsonValue>> Variables;
    for (const auto& Variable : Blueprint->NewVariables)
    {
        auto Description = MakeShared<FJsonObject>();
        Description->SetStringField(TEXT("name"), Variable.VarName.ToString());
        Description->SetStringField(TEXT("guid"), Variable.VarGuid.ToString());
        Description->SetObjectField(TEXT("type"), DescribePinType(Variable.VarType));
        Description->SetStringField(TEXT("defaultValue"), Variable.DefaultValue);
        Description->SetStringField(TEXT("repNotify"), Variable.RepNotifyFunc.ToString());
        FString Export;
        FBPVariableDescription::StaticStruct()->ExportText(Export, &Variable, nullptr, Blueprint, PPF_None, nullptr);
        Description->SetStringField(TEXT("export"), Export);
        Variables.Add(MakeShared<FJsonValueObject>(Description));
    }
    Report->SetArrayField(TEXT("variables"), Variables);
    Report->SetBoolField(TEXT("success"), true);
#else
    Report->SetBoolField(TEXT("supported"), false);
    Report->SetBoolField(TEXT("success"), false);
    Report->SetStringField(TEXT("error"), TEXT("Blueprint graph inspection requires an editor build."));
#endif
    return SerializeAudit(Report);
}
